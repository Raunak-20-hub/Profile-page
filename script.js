
/* =====================================
   LIGHT MODE FUNCTION
===================================== */

function setLight() {

    // Add light-mode class to body
    document.body.classList.add("light-mode");

}


/* =====================================
   DARK MODE FUNCTION
===================================== */

function setDark() {

    // Remove light-mode class from body
    document.body.classList.remove("light-mode");

}
